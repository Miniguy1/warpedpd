import com.watabou.utils.Random;

/** No tricks: a huge, ugly axe. Heavier than the Obsidian Greataxe is quick, it hits a little less hard
 *  and a little faster. */
public class Gravesplitter extends MeleeWeapon {

	{
		image = ItemSpriteSheet.GREATAXE;
		hitSound = Assets.Sounds.HIT_SLASH;
		hitSoundPitch = 0.85f;

		tier = 5;
		DLY = 1.1f;
	}

	@Override
	public int max( int lvl ) {
		return 7 * (tier + 1) +   //42 base
				lvl * (tier + 1);
	}
}
