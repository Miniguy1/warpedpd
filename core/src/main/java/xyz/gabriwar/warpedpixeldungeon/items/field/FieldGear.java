/** what the field items do to a fight */
public final class FieldGear {

	private FieldGear(){}

	/** the whetstone: while it lasts, a hit gets +2 and a fifth more */
	public static int onHit( Char enemy, int damage, boolean ranged ) {
		Hero h = Dungeon.hero;
		if (h == null || enemy == null) return damage;
		Sharpened s = h.buff( Sharpened.class );
		if (s == null) return damage;
		damage += 2 + damage / 5;
		s.use();
		return damage;
	}
}
