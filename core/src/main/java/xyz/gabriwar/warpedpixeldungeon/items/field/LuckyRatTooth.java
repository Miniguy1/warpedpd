/** a lucky rat tooth: carried, it brings in a tenth more of the gold you pick up */
public class LuckyRatTooth extends FieldItem {

	{
		image = ItemSpriteSheet.RAT_TOOTH;
	}

	/** the gold a pickup is worth to this hero: a tenth more with the tooth in the pack, and never less than one more coin */
	public static int goldBonus( Hero hero, int quantity ) {
		if (hero == null || hero.belongings == null || hero.belongings.getItem( LuckyRatTooth.class ) == null) return quantity;
		return Math.max( quantity + 1, Math.round( quantity * 1.1f ) );
	}

	@Override
	public int value() {
		return 40;
	}
}
